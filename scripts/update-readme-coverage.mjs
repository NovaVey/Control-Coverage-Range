#!/usr/bin/env node
// Embeds COVERAGE.md's own content into README.md, between two marker comments — so a
// reader landing on the repo doesn't have to build four sibling projects and run Docker
// to see a single cell (see README's own "Current coverage matrix" section, and the
// review this closes: "the README explains the legend without ever showing the table").
// Run by .github/workflows/range.yml's "Commit updated coverage baseline + rendered
// matrix" step on every green push to main, in the same commit as the baseline itself.
// Safe to run locally too — idempotent, no-ops if nothing changed.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url));
const COVERAGE_PATH = `${REPO_ROOT}COVERAGE.md`;
const README_PATH = `${REPO_ROOT}README.md`;

const START =
  '<!-- COVERAGE:START (auto-generated by scripts/update-readme-coverage.mjs on every green push to main — do not hand-edit this section, it will be overwritten) -->';
const END = '<!-- COVERAGE:END -->';

const coverage = readFileSync(COVERAGE_PATH, 'utf8').trim();
const readme = readFileSync(README_PATH, 'utf8');

const startIdx = readme.indexOf(START);
const endIdx = readme.indexOf(END);
if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
  throw new Error(
    `README.md is missing its COVERAGE:START/COVERAGE:END markers (looked for exactly:\n${START}\n...\n${END}\n) — add them where the matrix should be embedded before running this script`,
  );
}

const before = readme.slice(0, startIdx + START.length);
const after = readme.slice(endIdx);
const updated = `${before}\n\n${coverage}\n\n${after}`;

if (updated !== readme) {
  writeFileSync(README_PATH, updated, 'utf8');
  console.log("README.md's embedded coverage matrix updated.");
} else {
  console.log("README.md's embedded coverage matrix already up to date.");
}
